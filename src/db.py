"""Postgres 資料存取層：整個 pipeline（ingest / embed / classify / trend / recommend /
report / interact）共用同一份 Postgres 資料庫（Neon），這個模組集中管理 schema 定義與所有
讀寫函式，其他模組不直接寫 SQL，一律透過這裡提供的函式存取資料庫。
"""

import atexit
import os
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row, tuple_row
from psycopg.types.json import Jsonb
from psycopg_pool import ConnectionPool

# 本機開發時從專案根目錄的 .env 讀 DATABASE_URL（neon link 產生，已 gitignore）；
# 部署到 Render 時則由 Render Dashboard 設定同名環境變數，load_dotenv 不會覆蓋它。
load_dotenv(Path(__file__).resolve().parent.parent / ".env")

# 整個系統用到的資料表定義。用 CREATE TABLE IF NOT EXISTS 是為了讓 init_db()
# 可以每次啟動都安全地重複執行，不需要額外的 migration 機制。
# 時間欄位沿用 ISO 8601 字串（TEXT），跟 SQLite 時期的資料格式一致，字串排序即時間排序。
SCHEMA = """
CREATE TABLE IF NOT EXISTS items (
    source       TEXT NOT NULL,
    source_id    TEXT NOT NULL,
    title        TEXT NOT NULL,
    description  TEXT NOT NULL,
    url          TEXT NOT NULL,
    author       TEXT,
    category     TEXT,
    metric       BIGINT,
    published_at TEXT,
    fetched_at   TEXT NOT NULL,
    PRIMARY KEY (source, source_id)
);

CREATE TABLE IF NOT EXISTS metric_snapshots (
    source      TEXT NOT NULL,
    source_id   TEXT NOT NULL,
    metric      BIGINT NOT NULL,
    snapshot_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS embeddings (
    source     TEXT NOT NULL,
    source_id  TEXT NOT NULL,
    model      TEXT NOT NULL,
    vector     BYTEA NOT NULL,
    dim        INTEGER NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (source, source_id)
);

CREATE TABLE IF NOT EXISTS item_tags (
    source     TEXT NOT NULL,
    source_id  TEXT NOT NULL,
    tag        TEXT NOT NULL,
    score      DOUBLE PRECISION NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (source, source_id, tag)
);

CREATE TABLE IF NOT EXISTS trend_scores (
    source      TEXT NOT NULL,
    source_id   TEXT NOT NULL,
    score       DOUBLE PRECISION NOT NULL,
    basis       TEXT NOT NULL,
    computed_at TEXT NOT NULL,
    PRIMARY KEY (source, source_id)
);

CREATE TABLE IF NOT EXISTS interactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source     TEXT NOT NULL,
    source_id  TEXT NOT NULL,
    action     TEXT NOT NULL CHECK (action IN ('like', 'skip')),
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS narrations (
    source     TEXT NOT NULL,
    source_id  TEXT NOT NULL,
    narration  TEXT NOT NULL,
    model      TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (source, source_id)
);

CREATE INDEX IF NOT EXISTS metric_snapshots_source_idx ON metric_snapshots (source, snapshot_at);

-- 深讀清單：使用者丟進來的連結。抓取與翻譯由使用者電腦上的 reader_worker.py 處理
-- （Render 沒有 GPU、也連不到本機 Ollama），API 只負責收連結與提供閱讀。
CREATE TABLE IF NOT EXISTS reading_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url            TEXT NOT NULL UNIQUE,
    source         TEXT,
    source_id      TEXT,
    title          TEXT,
    title_zh       TEXT,
    authors        JSONB,
    published_at   TEXT,
    extraction     TEXT,
    warnings       JSONB,
    status         TEXT NOT NULL DEFAULT 'queued'
                   CHECK (status IN ('queued', 'fetching', 'translating', 'ready', 'failed')),
    error          TEXT,
    progress_done  INTEGER NOT NULL DEFAULT 0,
    progress_total INTEGER NOT NULL DEFAULT 0,
    read_progress  DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL
);

-- 原文區塊與譯文分開存：清單頁只讀 reading_items，不必搬動動輒幾百 KB 的全文。
CREATE TABLE IF NOT EXISTS reading_docs (
    item_id     BIGINT PRIMARY KEY REFERENCES reading_items (id) ON DELETE CASCADE,
    doc         JSONB NOT NULL,
    translation JSONB,
    updated_at  TEXT NOT NULL
);

-- 只有一列：本機翻譯 worker 最後一次回報的時間，閱讀頁用來顯示「翻譯站是否在線」。
CREATE TABLE IF NOT EXISTS reader_worker (
    id        INTEGER PRIMARY KEY CHECK (id = 1),
    model     TEXT,
    last_seen TEXT NOT NULL
);
"""


# 連線池：每次查詢都重新連線的話，光 TLS + 認證就要幾百毫秒，一頁要查幾十次（hydrate 對每個
# 項目各查一次），實測 /recommendations 從 SQLite 時期的瞬間變成 44 秒。所以改用連線池重用連線，
# 但 min_size=0 + max_idle=60：閒置 60 秒的連線會被關掉、一條都不留，Neon 才能在沒人用時休眠，
# 不會燒光免費方案每月的運算時數。
# DATABASE_URL 是 Neon 的 pooled endpoint（PgBouncer transaction mode），所以關掉 psycopg 的
# 自動 prepared statement（prepare_threshold=None），避免跨 PgBouncer 連線衝突。
_pool: ConnectionPool | None = None


def _reset(conn: psycopg.Connection) -> None:
    """連線歸還連線池時把 row_factory 還原成預設的 tuple：有些查詢會改成 dict_row，
    不還原的話下一個借到這條連線、用 tuple 拆解結果的函式會拿到 dict 而出錯。"""
    conn.row_factory = tuple_row


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        url = os.environ.get("DATABASE_URL")
        if not url:
            raise RuntimeError("DATABASE_URL 沒有設定：本機請在專案根目錄執行 neon link 產生 .env，部署環境請在 Render 設定環境變數。")
        _pool = ConnectionPool(
            url,
            min_size=0,
            max_size=4,
            max_idle=60,
            kwargs={"prepare_threshold": None, "connect_timeout": 15},
            reset=_reset,
            open=True,
        )
        atexit.register(_pool.close)
    return _pool


def get_connection():
    """從連線池借一條連線，搭配 with 使用：離開區塊時沒出錯就 commit、出錯就 rollback，再歸還連線池。"""
    return _get_pool().connection()


def init_db() -> None:
    """依 SCHEMA 建立所有資料表（已存在的表不會被動到），API 啟動、每支腳本執行前都會呼叫一次。"""
    with get_connection() as conn:
        for statement in SCHEMA.split(";"):
            if statement.strip():
                conn.execute(statement)


def upsert_items(items: list[dict]) -> int:
    """寫入項目，遇到已存在的（依 source+source_id 判斷）就略過，不覆蓋。

    回傳這次呼叫實際新增的筆數，讓呼叫端可以知道「這次抓到幾筆全新的項目」，
    而不是「這次總共處理了幾筆」。
    """
    with get_connection() as conn:
        cur = conn.cursor()
        cur.executemany(
            """
            INSERT INTO items
                (source, source_id, title, description, url, author, category, metric, published_at, fetched_at)
            VALUES
                (%(source)s, %(source_id)s, %(title)s, %(description)s, %(url)s, %(author)s, %(category)s,
                 %(metric)s, %(published_at)s, %(fetched_at)s)
            ON CONFLICT (source, source_id) DO NOTHING
            """,
            items,
        )
        return cur.rowcount


def record_snapshots(items: list[dict]) -> None:
    """不管項目本身是不是新的，每次抓取都幫每個項目多寫一筆指標快照（metric snapshot）。

    這是刻意設計成「每次都寫」而不是「只在項目是新的時候才寫」：
    之後計算「成長率」型的熱度分數（trend score）需要同一個項目在不同時間點的指標序列，
    只有持續累積快照才能還原出這條時間序列。
    """
    with get_connection() as conn:
        conn.cursor().executemany(
            """
            INSERT INTO metric_snapshots (source, source_id, metric, snapshot_at)
            VALUES (%(source)s, %(source_id)s, %(metric)s, %(fetched_at)s)
            """,
            items,
        )


def get_items_missing_embeddings() -> list[dict]:
    """找出 items 裡還沒有對應 embedding 紀錄的項目，供 embed.py 增量處理。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute(
            """
            SELECT items.source, items.source_id, items.title, items.description
            FROM items
            LEFT JOIN embeddings
                ON items.source = embeddings.source AND items.source_id = embeddings.source_id
            WHERE embeddings.source_id IS NULL
            """
        ).fetchall()
        return [dict(row) for row in rows]


def upsert_embeddings(rows: list[dict]) -> None:
    """寫入 embedding 向量。每筆 row 需包含：source, source_id, model, vector（bytes）, dim, created_at。"""
    with get_connection() as conn:
        conn.cursor().executemany(
            """
            INSERT INTO embeddings (source, source_id, model, vector, dim, created_at)
            VALUES (%(source)s, %(source_id)s, %(model)s, %(vector)s, %(dim)s, %(created_at)s)
            ON CONFLICT (source, source_id) DO UPDATE SET
                model = EXCLUDED.model, vector = EXCLUDED.vector, dim = EXCLUDED.dim, created_at = EXCLUDED.created_at
            """,
            rows,
        )


def get_all_embeddings() -> list[dict]:
    """讀出所有項目的 embedding 向量，供 classify.py / api.py 的語意搜尋做線性掃描比對。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute("SELECT source, source_id, vector, dim FROM embeddings").fetchall()
        return [dict(row) for row in rows]


def upsert_tags(rows: list[dict]) -> None:
    """寫入標籤分類結果。每筆 row 需包含：source, source_id, tag, score, created_at。"""
