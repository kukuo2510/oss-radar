# ---------------------------------------------------------------- 深讀清單

READING_LIST_COLUMNS = (
    "id, url, source, source_id, title, title_zh, authors, published_at, extraction, warnings, "
    "status, error, progress_done, progress_total, read_progress, created_at, updated_at"
)
# update_reading_item() 只允許改這些欄位，避免呼叫端傳進任意欄位名稱拼進 SQL。
READING_UPDATABLE = {
    "source", "source_id", "title", "title_zh", "authors", "published_at", "extraction", "warnings",
    "status", "error", "progress_done", "progress_total", "read_progress",
}
READING_JSON_FIELDS = {"authors", "warnings"}


def _utcnow() -> str:
    return datetime.now(timezone.utc).isoformat()


def add_reading_item(url: str) -> dict:
    """加入深讀清單；同一個網址已經在清單裡就直接回傳原本那筆，不重複加。"""
    now = _utcnow()
    with get_connection() as conn:
        conn.row_factory = dict_row
        return conn.execute(
            f"""
            INSERT INTO reading_items (url, created_at, updated_at) VALUES (%s, %s, %s)
            ON CONFLICT (url) DO UPDATE SET url = EXCLUDED.url
            RETURNING {READING_LIST_COLUMNS}
            """,
            (url, now, now),
        ).fetchone()


def count_pending_reading_items() -> int:
    with get_connection() as conn:
        return conn.execute(
            "SELECT COUNT(*) FROM reading_items WHERE status IN ('queued', 'fetching', 'translating')"
        ).fetchone()[0]


def list_reading_items() -> list[dict]:
    """清單頁用：不帶全文，只多帶重點整理的那一句話（one_line），讓使用者不用點進去就知道在講什麼。"""
    cols = ", ".join(f"reading_items.{c.strip()}" for c in READING_LIST_COLUMNS.split(","))
    with get_connection() as conn:
        conn.row_factory = dict_row
        return conn.execute(
            f"""
            SELECT {cols}, reading_docs.translation -> 'summary' ->> 'one_line' AS one_line
            FROM reading_items LEFT JOIN reading_docs ON reading_docs.item_id = reading_items.id
            ORDER BY reading_items.created_at DESC
            """
        ).fetchall()


def get_reading_item(item_id: int, with_content: bool = False) -> dict | None:
    """with_content=True 時一併帶回原文區塊（doc）與譯文（translation），給閱讀頁用。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        if with_content:
            cols = ", ".join(f"reading_items.{c.strip()}" for c in READING_LIST_COLUMNS.split(","))
            return conn.execute(
                f"""
                SELECT {cols}, reading_docs.doc, reading_docs.translation
                FROM reading_items LEFT JOIN reading_docs ON reading_docs.item_id = reading_items.id
                WHERE reading_items.id = %s
                """,
                (item_id,),
            ).fetchone()
        return conn.execute(f"SELECT {READING_LIST_COLUMNS} FROM reading_items WHERE id = %s", (item_id,)).fetchone()


def update_reading_item(item_id: int, **fields) -> None:
    unknown = set(fields) - READING_UPDATABLE
    if unknown:
        raise ValueError(f"不能更新的欄位：{unknown}")
    if not fields:
        return
    values = [Jsonb(v) if k in READING_JSON_FIELDS and v is not None else v for k, v in fields.items()]
    sets = ", ".join(f"{k} = %s" for k in fields)
    with get_connection() as conn:
        conn.execute(
            f"UPDATE reading_items SET {sets}, updated_at = %s WHERE id = %s",
            (*values, _utcnow(), item_id),
        )


def delete_reading_item(item_id: int) -> bool:
    with get_connection() as conn:
        return conn.execute("DELETE FROM reading_items WHERE id = %s", (item_id,)).rowcount > 0


def save_reading_doc(item_id: int, doc: dict) -> None:
    with get_connection() as conn:
        conn.execute(
            """
            INSERT INTO reading_docs (item_id, doc, updated_at) VALUES (%s, %s, %s)
            ON CONFLICT (item_id) DO UPDATE SET doc = EXCLUDED.doc, updated_at = EXCLUDED.updated_at
            """,
            (item_id, Jsonb(doc), _utcnow()),
        )


def save_reading_translation(item_id: int, translation: dict) -> None:
    with get_connection() as conn:
        conn.execute(
            "UPDATE reading_docs SET translation = %s, updated_at = %s WHERE item_id = %s",
            (Jsonb(translation), _utcnow(), item_id),
        )


def get_reading_doc(item_id: int) -> tuple[dict | None, dict | None]:
    with get_connection() as conn:
        row = conn.execute("SELECT doc, translation FROM reading_docs WHERE item_id = %s", (item_id,)).fetchone()
        return (row[0], row[1]) if row else (None, None)


def claim_next_reading_item() -> dict | None:
    """worker 取下一筆排隊中的項目並標成 fetching。只有一個 worker，SKIP LOCKED 是保險。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        return conn.execute(
            f"""
            UPDATE reading_items SET status = 'fetching', error = NULL, updated_at = %s
            WHERE id = (
                SELECT id FROM reading_items WHERE status = 'queued'
                ORDER BY created_at LIMIT 1 FOR UPDATE SKIP LOCKED
            )
            RETURNING {READING_LIST_COLUMNS}
            """,
            (_utcnow(),),
        ).fetchone()


def requeue_interrupted_reading_items() -> int:
    """worker 啟動時呼叫：上次執行到一半被中斷（電腦關機）的項目放回佇列，譯文已存的部分會沿用。"""
    with get_connection() as conn:
        return conn.execute(
            "UPDATE reading_items SET status = 'queued', updated_at = %s WHERE status IN ('fetching', 'translating')",
            (_utcnow(),),
        ).rowcount


def worker_heartbeat(model: str) -> None:
    with get_connection() as conn:
        conn.execute(
            """
            INSERT INTO reader_worker (id, model, last_seen) VALUES (1, %s, %s)
            ON CONFLICT (id) DO UPDATE SET model = EXCLUDED.model, last_seen = EXCLUDED.last_seen
            """,
            (model, _utcnow()),
        )


def get_worker_status() -> dict | None:
    with get_connection() as conn:
        conn.row_factory = dict_row
        return conn.execute("SELECT model, last_seen FROM reader_worker WHERE id = 1").fetchone()


def reading_ids_missing_summary() -> list[int]:
    """已經翻好、但譯文裡還沒有重點整理的項目（重點整理功能加入前翻好的文章要補）。"""
    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT reading_docs.item_id FROM reading_docs
            JOIN reading_items ON reading_items.id = reading_docs.item_id
            WHERE reading_items.status = 'ready' AND reading_docs.translation IS NOT NULL
              AND jsonb_typeof(reading_docs.translation -> 'summary') IS DISTINCT FROM 'object'
            """
        ).fetchall()
    return [r[0] for r in rows]
