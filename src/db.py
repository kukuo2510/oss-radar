def get_all_trend_scores() -> dict:
    """回傳 (source, source_id) -> 熱度分數 的對照表，方便其他模組整批查詢。"""
    with get_connection() as conn:
        rows = conn.execute("SELECT source, source_id, score FROM trend_scores").fetchall()
        return {(source, source_id): score for source, source_id, score in rows}


def record_interaction(source: str, source_id: str, action: str) -> None:
    """記錄一次使用者互動（按讚或略過），時間戳記統一用 UTC，避免跨時區比較時出錯。"""
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO interactions (source, source_id, action, created_at) VALUES (%s, %s, %s, %s)",
            (source, source_id, action, datetime.now(timezone.utc).isoformat()),
        )


def get_latest_interactions() -> dict:
    """回傳 (source, source_id) -> 最新一次的動作（'like'/'skip'）。

    同一個項目可能被使用者按讚後又改成略過（或反過來），這裡只取每組
    (source, source_id) 裡 id 最大（也就是最新）的那一筆，讓「改變心意」可以覆蓋掉舊的判斷。
    """
    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT source, source_id, action FROM interactions
            WHERE id IN (SELECT MAX(id) FROM interactions GROUP BY source, source_id)
            """
        ).fetchall()
        return {(source, source_id): action for source, source_id, action in rows}


def get_item(source: str, source_id: str) -> dict | None:
    """依 (source, source_id) 查單一項目的完整欄位；查無資料回傳 None。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        row = conn.execute(
            "SELECT * FROM items WHERE source = %s AND source_id = %s", (source, source_id)
        ).fetchone()
        return dict(row) if row else None


def get_items_by_keys(keys: list[tuple[str, str]]) -> dict:
    """一次查回多個項目，回傳 (source, source_id) -> 項目欄位。

    給 API 批次組裝清單用：連線到 Neon 每次查詢都有網路往返成本，逐筆查 20 個項目
    （每筆再查一次標籤）實測要 20 秒，改成一次查完只要一次往返。
    """
    if not keys:
        return {}
    sources, ids = [k[0] for k in keys], [k[1] for k in keys]
    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute(
            """
            SELECT items.* FROM items
            JOIN unnest(%s::text[], %s::text[]) AS k(source, source_id) USING (source, source_id)
            """,
            (sources, ids),
        ).fetchall()
        return {(r["source"], r["source_id"]): dict(r) for r in rows}


def get_tags_for_keys(keys: list[tuple[str, str]]) -> dict:
    """一次查回多個項目的標籤，回傳 (source, source_id) -> [{tag, score}, ...]（分數高到低）。"""
    if not keys:
        return {}
    sources, ids = [k[0] for k in keys], [k[1] for k in keys]
    result: dict = {k: [] for k in keys}
    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT item_tags.source, item_tags.source_id, tag, score FROM item_tags
            JOIN unnest(%s::text[], %s::text[]) AS k(source, source_id) USING (source, source_id)
            ORDER BY score DESC
            """,
            (sources, ids),
        ).fetchall()
    for source, source_id, tag, score in rows:
        result.setdefault((source, source_id), []).append({"tag": tag, "score": score})
    return result


def get_items(source: str | None = None, tag: str | None = None, limit: int = 50, offset: int = 0) -> list[dict]:
    """分頁列出項目，可選擇依來源（source）與標籤（tag）篩選。

    SQL 是用字串組合動態拼出來的：只有在有指定 tag 時才 JOIN item_tags 表、
    只有在有指定 source/tag 時才加對應的 WHERE 條件，避免不需要篩選時多做不必要的 JOIN。
    """
    query = "SELECT DISTINCT items.* FROM items"
    params: list = []
    where = []
    if tag:
        query += " JOIN item_tags ON items.source = item_tags.source AND items.source_id = item_tags.source_id"
        where.append("item_tags.tag = %s")
        params.append(tag)
    if source:
        where.append("items.source = %s")
        params.append(source)
    if where:
        query += " WHERE " + " AND ".join(where)
    query += " ORDER BY items.published_at DESC LIMIT %s OFFSET %s"
    params += [limit, offset]

    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute(query, params).fetchall()
        return [dict(row) for row in rows]


def get_item_tags(source: str, source_id: str) -> list[dict]:
    """取得單一項目的所有標籤，依分數（score）由高到低排序。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute(
            "SELECT tag, score FROM item_tags WHERE source = %s AND source_id = %s ORDER BY score DESC",
            (source, source_id),
        ).fetchall()
        return [dict(row) for row in rows]


def get_tags_with_counts() -> list[dict]:
    """列出所有標籤與各自被使用的次數，依次數由多到少排序，供前端做標籤雲/篩選清單。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute(
            "SELECT tag, COUNT(*) as count FROM item_tags GROUP BY tag ORDER BY count DESC"
        ).fetchall()
        return [dict(row) for row in rows]


def get_top_trend_scores(limit: int = 20) -> list[dict]:
    """取出熱度分數最高的前 N 筆，作為「熱門排行榜」的資料來源。"""
    with get_connection() as conn:
        conn.row_factory = dict_row
        rows = conn.execute(
            "SELECT source, source_id, score, basis FROM trend_scores ORDER BY score DESC LIMIT %s",
            (limit,),
        ).fetchall()
        return [dict(row) for row in rows]


